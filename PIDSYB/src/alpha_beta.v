// ============================================================================
// alpha_beta.v  —  α-β 滤波器（位置 + 速度的最小状态估计器）
//
// 【原理】
//   假设摆杆角度按匀速变化（θ[k] = θ[k-1] + ω·T），但模型有误差、ADC 有噪声。
//   每拍做「预测 → 比较 → 校正」：
//
//     预测:  x⁻ = x̂ + v̂
//     新息:  r  = z - x⁻
//     校正:  x̂ ← x⁻ + α·r
//            v̂ ← v̂ + β·r
//
//   数学上它就是「匀速模型 + 白噪声」下卡尔曼滤波的稳态形式，
//   α、β 就是收敛后的卡尔曼增益。
//
// 【为什么对倒立摆有用】
//   角度环 D 项原来的做法是 5ms 裸差分：ang_d5 = ang_err - ang_err_prev。
//   ADC 量化噪声 σ≈22 计数，差分后噪声 σ≈31 计数还要乘 BAL_KD=180，
//   得到 ±5580 PWM 的纯噪声（已超过满量程 5175）—— 等于没有阻尼。
//   α-β 直接给出【平滑的速度估计】（σ≈0.9），噪声降到 1/34，
//   且不对位置做任何低通，因此不引入低通相位滞后。
//
// 【稳定性】
//   0 < α < 2 ，  0 < β < 4 - 2α
//   常用整定（Benedict-Bordner，双极点重合）：β = α² / (2 - α)
//     α = 0.20  →  β = 0.0222   （推荐起点）
//     α = 0.10  →  β = 0.0053   （更平滑）
//     α = 0.50  →  β = 0.167    （跟得更快，噪声更大）
//
// 【定点】
//   内部状态 Q8（8 位小数）。α/β 也是 Q8（0~0.996），运行时可写。
//
// 【⚠ 关于输出打拍与延迟】
//   x_out/v_out 是寄存器输出（在 tick 边沿更新）。
//   如果控制逻辑在【同一个 tick_5ms 边沿】采样，拿到的就是上一拍的滤波值，
//   相当于在角度环里凭空多出 5ms 纯延迟 —— 会吃掉 D 项的相位超前。
//   解决办法不是去掉寄存器（那样两级乘法会串在一个 20ns 时钟里，
//   实测 setup slack 直接 -12ns），而是把【控制节拍延后 1 个时钟】：
//   滤波器在 tick 边沿更新状态，控制逻辑在下一个时钟沿采样它。
//   代价从 5ms 降到 20ns，可忽略。
//   → pendulum_ctrl.v 里的 tick_c 就是做这件事的。
// ============================================================================
module alpha_beta #(
    parameter integer ALPHA_Q8 = 51,      // 默认 α = 51/256 ≈ 0.199
    parameter integer BETA_Q8  = 6        // 默认 β =  6/256 ≈ 0.0234
)(
    input  wire               clk,
    input  wire               rst_n,
    input  wire               tick,        // 5ms 控制节拍（单拍脉冲）
    input  wire [15:0]        alpha_q8,    // 运行时 α（低 8 位有效）
    input  wire [15:0]        beta_q8,     // 运行时 β（低 8 位有效）
    input  wire [11:0]        z,           // 角度测量值（12-bit ADC）

    output reg  [11:0]        x_out,       // 滤波后角度（与 ADC 同标度）
    output reg  signed [15:0] v_out        // 估计角速度（计数 / 拍）
);

    wire [7:0] a = alpha_q8[7:0];
    wire [7:0] b = beta_q8 [7:0];

    reg signed [23:0] x_hat;               // Q8 位置估计
    reg signed [23:0] v_hat;               // Q8 速度估计（计数/拍）
    reg               init;                // 是否已完成首拍初始化

    // ------------------------------------------------------------------------
    // 预测
    // ------------------------------------------------------------------------
    wire signed [23:0] z_q8   = $signed({4'd0, z, 8'd0});   // z << 8
    wire signed [24:0] x_pred = x_hat + v_hat;

    // ------------------------------------------------------------------------
    // 新息（预测与测量的差）
    // ------------------------------------------------------------------------
    wire signed [25:0] r_raw = z_q8 - x_pred;

    // 限幅：|r| ≤ 2^22（Q8 下 ±16384 计数，约为 ADC 满量程的 4 倍）。
    //   作用只是防止非法输入让 x̂/v̂ 跑飞；正常 12-bit ADC 永远碰不到。
    //   ⚠ 早期版本用 ±2^19（= ±2048 计数），上电首帧 ADC 未就绪、
    //     第二帧直接跳到 3227 时会被削掉，导致收敛变慢 —— 已放宽。
    //   位宽校验：2^22 × 255 = 2^30 < 2^33，34-bit 乘积不溢出。
    wire signed [25:0] r = (r_raw >  26'sd4194303) ?  26'sd4194303 :
                           (r_raw < -26'sd4194304) ? -26'sd4194304 : r_raw;

    // ------------------------------------------------------------------------
    // 校正量
    //   +128 是四舍五入，避免算术右移的向下取整造成单向偏置
    // ------------------------------------------------------------------------
    wire signed [33:0] r_a = r * $signed({2'b0, a});
    wire signed [33:0] r_b = r * $signed({2'b0, b});
    wire signed [33:0] dx  = (r_a + 34'sd128) >>> 8;
    wire signed [33:0] dv  = (r_b + 34'sd128) >>> 8;

    // ------------------------------------------------------------------------
    // 下一拍状态
    //   ⚠ 必须显式 $signed()：Verilog 里 dv[24:0] 这类部分选择是【无符号】的，
    //     与有符号数相加会让整个表达式变成无符号，负的校正量被当成巨大正数。
    //     （取低 24 位后按模运算结果仍然正确，但综合工具会报符号/位宽告警，
    //      且一旦将来改了位宽就会真的出错 —— 这里写清楚。）
    // ------------------------------------------------------------------------
    wire signed [24:0] dx25   = $signed(dx[24:0]);
    wire signed [24:0] dv25   = $signed(dv[24:0]);
    wire signed [24:0] x_nxt  = init ? (x_pred + dx25) : $signed(z_q8);
    wire signed [24:0] v_nxt  = init ? (v_hat  + dv25) : 25'sd0;

    // ------------------------------------------------------------------------
    // 输出值（四舍五入取整）
    //   init=0 时 x_nxt 直接取 z_q8，所以输出等效于直通测量值，
    //   上电后第一拍之前不会出现"半个角度"的怪读数。
    // ------------------------------------------------------------------------
    wire signed [24:0] x_rnd = (x_nxt + 25'sd128) >>> 8;
    wire signed [24:0] v_rnd = (v_nxt + 25'sd128) >>> 8;

    wire [11:0] x_sat =
        (x_rnd > 25'sd4095)   ? 12'd4095 :
        (x_rnd < 25'sd0)      ? 12'd0    : x_rnd[11:0];

    wire signed [15:0] v_sat =
        (v_rnd > 25'sd32767)  ?  16'sd32767 :
        (v_rnd < -25'sd32768) ? -16'sd32768 : v_rnd[15:0];

    // ------------------------------------------------------------------------
    // 状态更新 + 输出寄存器（只在 tick 边沿推进）
    // ------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n)
        if(!rst_n) begin
            x_hat <= 24'sd0;
            v_hat <= 24'sd0;
            init  <= 1'b0;
            x_out <= 12'd0;
            v_out <= 16'sd0;
        end else if(tick) begin
            x_hat <= $signed(x_nxt[23:0]);
            v_hat <= $signed(v_nxt[23:0]);
            init  <= 1'b1;
            x_out <= x_sat;
            v_out <= v_sat;
        end

endmodule
